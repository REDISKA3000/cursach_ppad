def main():
    parser = MockLLM()
    failures = []

    for sample in SAMPLES:
        profile = parser.parse_vacancy_profile(sample["text"])
        for check in sample["checks"]:
            if not check(profile):
                failures.append(sample["name"])
                break

    if failures:
        raise SystemExit(f"Failed vacancy samples: {failures}")

    print("vacancy parsing sample checks passed")


if __name__ == "__main__":
    main()
